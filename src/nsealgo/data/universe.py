"""Default trading universe: most liquid symbols by median daily turnover in a fixed
early window (the first year of clean data, to limit survivorship bias)."""

from datetime import date
from pathlib import Path

import pandas as pd
import yaml

UNIVERSE_WARNING = (
    "Universe membership is NOT point-in-time: the raw dataset only contains symbols "
    "that are large caps today, so survivorship bias is built in and cannot be removed "
    "by choosing on first-year turnover."
)


def rank_by_turnover(daily: pd.DataFrame, start: date, end: date, n: int) -> pd.DataFrame:
    """Top `n` symbols by median daily rupee turnover over sessions in [start, end]."""
    window = daily[(daily["session_date"] >= start) & (daily["session_date"] <= end)]
    ranked = (
        window.groupby("symbol")
        .agg(median_turnover=("turnover", "median"), sessions=("turnover", "size"))
        .sort_values(["median_turnover", "sessions"], ascending=False)
        .reset_index()
    )
    return ranked.head(n)


def write_universe_yaml(path: Path, ranked: pd.DataFrame, start: date, end: date) -> None:
    body = {
        "selection": {
            "method": "median_daily_turnover",
            "start": start.isoformat(),
            "end": end.isoformat(),
            "top_n": len(ranked),
        },
        "symbols": ranked["symbol"].tolist(),
        "median_turnover_crore": {
            s: round(float(t) / 1e7, 2)
            for s, t in zip(ranked["symbol"], ranked["median_turnover"], strict=True)
        },
    }
    header = (
        "# Generated by scripts/build_data.py; edit by re-running, not by hand.\n"
        f"# WARNING: {UNIVERSE_WARNING}\n"
    )
    path.write_text(header + yaml.safe_dump(body, sort_keys=False), encoding="utf-8")
